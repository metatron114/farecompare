def province_of(city: str) -> str | None:
    """城市 -> 省级行政区。"""
    c = (city or "").strip().rstrip("市")
    if c in CITY_PROVINCE:
        return CITY_PROVINCE[c]
    if c in PROVINCE_CAPITAL:
        return c
    return None


def capital_of(city: str) -> str | None:
    """城市 -> 所在省的省会（本身是省会则返回自身）。"""
    prov = province_of(city)
    if not prov:
        return None
    return PROVINCE_CAPITAL.get(prov)


def tier_of(city: str) -> int:
    c = (city or "").strip().rstrip("市")
    return HUB_TIER.get(c, 0)


def all_hubs() -> list[str]:
    """全部可作为中转枢纽的城市（省会 + 各级枢纽），按重要度降序。"""
    out = set(PROVINCE_CAPITAL.values()) | set(HUB_TIER.keys())
    return sorted(out, key=lambda c: (-tier_of(c), c))


def describe() -> dict:
    return {
        "provinces": len(PROVINCE_CAPITAL),
        "cities_mapped": len(CITY_PROVINCE),
        "hubs": len(all_hubs()),
        "tier3": [c for c in HUB_TIER if HUB_TIER[c] == 3],
        "tier2_count": sum(1 for c in HUB_TIER if HUB_TIER[c] == 2),
        "tier1_count": sum(1 for c in HUB_TIER if HUB_TIER[c] == 1),
    }


